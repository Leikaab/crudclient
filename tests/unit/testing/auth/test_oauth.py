from datetime import datetime, timedelta

from freezegun import freeze_time

from crudclient.auth import CustomAuth
from crudclient.testing.auth.oauth_mock import OAuthMock

# --- Test Initialization ---


def test_oauth_mock_init_defaults() -> None:
    """Test default initialization."""
    mock = OAuthMock()
    assert mock.client_id == "client_id"
    assert mock.client_secret == "client_secret"
    assert mock.token_url == "https://example.com/oauth/token"
    assert mock.authorize_url == "https://example.com/oauth/authorize"
    assert mock.redirect_uri == "https://app.example.com/callback"
    assert mock.scope == "read write"

    # Check token manager state (indirectly)
    assert mock.token_manager.current_access_token is not None
    initial_token = mock.token_manager.current_access_token
    assert mock.token_manager.validate_token(initial_token) is True

    # Check auth strategy
    assert isinstance(mock.auth_strategy, CustomAuth)
    headers = mock.auth_strategy.prepare_request_headers()
    assert headers == {"Authorization": f"Bearer {initial_token}"}


