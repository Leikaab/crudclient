@freeze_time("2023-01-01 12:00:00")
def test_handle_auth_error_expired_refreshable_base() -> None:
    """Test handle_auth_error uses base refresh simulation."""
    mock = OAuthMock().with_access_token("expired_token")
    mock.with_expired_token()  # Expire the OAuth token
    # Enable base class refresh simulation
    mock.with_refresh_token("base_refresh_key")

    assert mock.is_token_expired() is True  # Checks base class expired flag
    assert mock.can_refresh_token() is True  # Checks base class refresh possibility

    handled = mock.handle_auth_error(None)  # type: ignore
    assert handled is True  # Base refresh simulation succeeded
    assert mock.refresh_attempts == 1


@freeze_time("2023-01-01 12:00:00")
def test_handle_auth_error_expired_not_refreshable_base() -> None:
    """Test handle_auth_error when base refresh not possible."""
    mock = OAuthMock().with_access_token("expired_token")
    mock.with_expired_token()  # Expire the OAuth token
    # DO NOT enable base class refresh simulation

    assert mock.is_token_expired() is True
    assert mock.can_refresh_token() is False  # Base refresh not possible

    handled = mock.handle_auth_error(None)  # type: ignore
    assert handled is False


@freeze_time("2023-01-01 12:00:00")
def test_handle_auth_error_not_expired_base() -> None:
    """Test handle_auth_error when token not expired (base check)."""
    mock = OAuthMock().with_access_token("valid_token")
    mock.with_token_expiration(3600)  # Not expired
    mock.with_refresh_token("base_refresh_key")  # Enable base refresh

    assert mock.is_token_expired() is False  # Base check

    handled = mock.handle_auth_error(None)  # type: ignore
    assert handled is False


def test_get_auth_strategy() -> None:
    """Test getting the underlying auth strategy."""
    mock = OAuthMock()
    strategy = mock.get_auth_strategy()
    assert isinstance(strategy, CustomAuth)
    # Check if the callback produces the correct header
    headers = strategy.prepare_request_headers()
    assert "Authorization" in headers
    assert headers["Authorization"].startswith("Bearer ")
