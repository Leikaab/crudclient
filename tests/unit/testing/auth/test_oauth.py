def test_with_access_token() -> None:
    """Test setting a specific access token."""
    mock = OAuthMock()
    initial_token = mock.token_manager.current_access_token
    mock.with_access_token("new_token_123")

    assert mock.token_manager.current_access_token == "new_token_123"
    assert mock.token_manager.validate_token("new_token_123") is True
    # Check if old token might still be valid if not explicitly revoked/expired
    assert mock.token_manager.validate_token(initial_token) is True

    # Check auth strategy update
    headers = mock.auth_strategy.prepare_request_headers()
    assert headers == {"Authorization": "Bearer new_token_123"}


def test_with_refresh_token() -> None:
    """Test associating a refresh token."""
    mock = OAuthMock().with_access_token("acc_token")
    mock.with_refresh_token("ref_token_abc")
    assert mock.token_manager.current_refresh_token == "ref_token_abc"
    assert mock.token_manager.refresh_tokens["ref_token_abc"] == "acc_token"


def test_with_token_expiration() -> None:
    """Test setting token expiration."""
    with freeze_time("2023-01-01 12:00:00") as frozen_time:
        mock = OAuthMock().with_access_token("exp_token")
        mock.with_token_expiration(expires_in_seconds=60)

        token_data = mock.token_manager.access_tokens["exp_token"]
        assert token_data["expires_at"] == datetime(2023, 1, 1, 12, 1, 0)

        assert mock.token_manager.validate_token("exp_token") is True
        frozen_time.tick(delta=timedelta(seconds=61))
        assert mock.token_manager.validate_token("exp_token") is False


@freeze_time("2023-01-01 12:00:00")
def test_with_expired_token() -> None:
    """Test setting token as already expired."""
    mock = OAuthMock().with_access_token("already_expired")
    mock.with_expired_token()

    token_data = mock.token_manager.access_tokens["already_expired"]
    assert token_data["expires_at"] < datetime(2023, 1, 1, 12, 0, 0)
    assert mock.token_manager.validate_token("already_expired") is False


